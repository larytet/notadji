#!/usr/bin/env python3
"""CFR tables: the soft-clip gain table and the clipping-product filter (design/26-papr-dpd.md section 1).
Usage: gen_cfr_tables.py            writes rtl/26-papr-dpd/cfr_coef_pkg.sv (63 taps)"""
import sys
from pathlib import Path

import numpy as np

TAPS = 63
CUT = 0.14          # cycles per sample, between the pass band edge 0.115 and the stop band edge 0.165 (OS = 4)
BETA = 5.0


def fir_coeffs(taps=TAPS, cut=CUT, beta=BETA):
    from scipy import signal
    h = signal.firwin(taps, cut * 2, window=("kaiser", beta))
    h = h / h.sum()
    return [int(round(v * 32768)) for v in h]


def clip_table(a):
    """Gain table of 256 entries (Q15) for the magnitude threshold a (0 to 1, fraction of full scale): index = min(255, m2 >> 22),
    m2 = I^2 + Q^2 in Q30, evaluated in the middle of each bin."""
    t = []
    for i in range(256):
        m2 = (i + 0.5) * 2 ** 22 / 2 ** 30                 # fraction of full-scale power
        mag = np.sqrt(m2)
        gain = 1.0 if mag <= a else a / mag
        t.append(int(round(min(1.0, gain) * 32768)))
    return t


def main():
    c = fir_coeffs()
    out = Path(__file__).resolve().parent.parent / "rtl" / "26-papr-dpd" / "cfr_coef_pkg.sv"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["// generated by scripts/gen_cfr_tables.py: Kaiser (beta 5) low-pass, 63 taps, cut 0.14 cycles per sample, Q15, sum = 32768",
             "package cfr_coef_pkg;",
             "  /* verilator lint_off UNUSED */",
             f"  localparam int CFR_TAPS = {len(c)};",
             "  // coefficient k is CFR_COEF_FLAT[16 k +: 16], two's complement",
             f"  localparam logic [{16 * len(c) - 1}:0] CFR_COEF_FLAT = {{"]
    lines.append(",\n".join("    16'h%04x" % (v & 0xFFFF) for v in reversed(c)))
    lines.append("  };")
    lines.append("  /* verilator lint_on UNUSED */")
    lines.append("endpackage")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: sum {sum(c)}, centre {c[len(c) // 2]}")


if __name__ == "__main__":
    main()
