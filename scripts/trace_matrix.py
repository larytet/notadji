#!/usr/bin/env python3
"""Generate spec/09-traceability-matrix.md from spec/01-system-requirements.md.

Usage: python3 -I scripts/trace_matrix.py
The test group for each requirement comes from its ID prefix (see GROUPS and spec/08-verification-plan.md).
Requirements whose verification includes T (test) get a test group; the generator also fails if a requirement
has no verification method, so the SRS cannot drift away from the plan.
"""
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "spec" / "01-system-requirements.md"
DST = ROOT / "spec" / "09-traceability-matrix.md"

GROUPS = {
    "SYS": "TG-SYS system and range",
    "VID": "TG-VID video pipeline",
    "LAT": "TG-LAT latency rig",
    "PHY": "TG-PHY baseband conformance",
    "MAC": "TG-MAC protocol",
    "RF": "TG-RF conducted RF",
    "ANT": "TG-ANT antenna and VSWR",
    "ADA": "TG-ADA spectrum and hopping",
    "CAL": "TG-CAL calibration",
    "THM": "TG-THM thermal",
    "PWR": "TG-PWR power",
    "SEC": "TG-SEC security",
    "REG": "TG-REG regulatory",
    "ENV": "TG-ENV environmental",
    "IF": "TG-IF interfaces",
    "SW": "TG-SW software",
    "HSI": "TG-HSI hardware-software integration",
    "PRO": "TG-PRO prototype",
    "ASC": "TG-ASC ASIC",
    "TST": "TG-TST test infrastructure",
}


@dataclass(frozen=True)
class Req:
    rid: str
    text: str
    pri: str
    phase: str
    ver: str


def parse(path: Path) -> list[Req]:
    """Parse requirement rows by splitting on the table separator (empty Phase cells are allowed)."""
    reqs = []
    for line in path.read_text().splitlines():
        if not re.match(r"\| [A-Z]{2,4}-\d{3} \|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 5 or not re.fullmatch(r"[TAIDS](,[TAIDS])*", cells[4]):
            continue  # reported by main() as a parse error
        reqs.append(Req(cells[0], cells[1], cells[2], cells[3] or "P1,P2", cells[4]))
    return reqs


def main() -> int:
    reqs = parse(SRC)
    all_rows = [ln for ln in SRC.read_text().splitlines() if re.match(r"\| [A-Z]{2,4}-\d{3} \|", ln)]
    if len(reqs) != len(all_rows):
        print(f"ERROR: parsed {len(reqs)} of {len(all_rows)} requirement rows", file=sys.stderr)
        return 1
    out = ["# 09 - Traceability Matrix", "",
           "Generated by `scripts/trace_matrix.py` from `01-system-requirements.md`. Do not edit by hand.", "",
           f"Requirements: {len(reqs)}", "",
           "| ID | Summary | Pri | Phase | Verification | Test group |", "|---|---|---|---|---|---|"]
    for r in reqs:
        prefix = r.rid.split("-")[0]
        summary = re.sub(r"\s+", " ", r.text.split(". ")[0])[:90].replace("|", "/")
        out.append(f"| {r.rid} | {summary} | {r.pri} | {r.phase} | {r.ver} | {GROUPS[prefix]} |")
    by_method = {}
    for r in reqs:
        for v in r.ver.split(","):
            by_method[v] = by_method.get(v, 0) + 1
    out += ["", "## Counts by verification method", "", "| Method | Requirements |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sorted(by_method.items())]
    DST.write_text("\n".join(out) + "\n")
    print(f"wrote {DST} ({len(reqs)} requirements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
