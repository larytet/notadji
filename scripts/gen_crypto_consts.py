#!/usr/bin/env python3
"""Generate the constant tables of the firmware crypto code from their definitions (no constants typed by hand):
fw/33-framework/sha2_k.h (SHA-256 and SHA-512 round constants and initial values) and curve25519_k.h (field constants as 16 limbs of 16 bits)."""
from pathlib import Path
OUT = Path(__file__).resolve().parent.parent / "fw" / "33-framework"

def primes(n):
    r, k = [], 2
    while len(r) < n:
        if all(k % p for p in r): r.append(k)
        k += 1
    return r

def iroot(x, n):
    lo, hi = 0, 1 << ((x.bit_length() // n) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** n <= x: lo = mid
        else: hi = mid - 1
    return lo

def frac_root(p, n, bits):
    return iroot(p << (n * bits), n) & ((1 << bits) - 1)

def arr(name, ty, vals, w, per):
    s = f"static const {ty} {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(f"0x{v:0{w}x}{'ull' if w == 16 else 'u'}" for v in vals[i:i + per]) + ",\n"
    return s + "};\n"

P = primes(80)
k256 = [frac_root(p, 3, 32) for p in P[:64]]
h256 = [frac_root(p, 2, 32) for p in P[:8]]
k512 = [frac_root(p, 3, 64) for p in P]
h512 = [frac_root(p, 2, 64) for p in P[:8]]
s = "/* generated by scripts/gen_crypto_consts.py: fractional parts of the cube and square roots of the first primes (FIPS 180-4) */\n#ifndef SHA2_K_H\n#define SHA2_K_H\n"
s += arr("sha256_k", "uint32_t", k256, 8, 8) + arr("sha256_h0", "uint32_t", h256, 8, 8)
s += arr("sha512_k", "uint64_t", k512, 16, 4) + arr("sha512_h0", "uint64_t", h512, 16, 4) + "#endif\n"
(OUT / "sha2_k.h").write_text(s)

p = 2 ** 255 - 19
d = (-121665 * pow(121666, p - 2, p)) % p
I = pow(2, (p - 1) // 4, p)
By = 4 * pow(5, p - 2, p) % p
u = (By * By - 1) % p; v = (d * By * By + 1) % p
x = pow(u * pow(v, p - 2, p) % p, (p + 3) // 8, p)
if (v * x * x - u) % p: x = x * I % p
assert (v * x * x - u) % p == 0
if x & 1: x = p - x                 # the base point has the even x
def limbs(v): return [(v >> (16 * i)) & 0xFFFF for i in range(16)]
t = "/* generated by scripts/gen_crypto_consts.py: field constants of curve25519/ed25519 as 16 limbs of 16 bits (little endian) */\n#ifndef CURVE25519_K_H\n#define CURVE25519_K_H\n"
for name, val in (("K_D", d), ("K_D2", 2 * d % p), ("K_X", x), ("K_Y", By), ("K_I", I)):
    t += f"static const int64_t {name}[16] = {{" + ", ".join(f"0x{l:04x}" for l in limbs(val)) + "};\n"
t += "#endif\n"
(OUT / "curve25519_k.h").write_text(t)
print("generated; base point x =", x)
