#!/usr/bin/env python3
"""Generate rtl/12-fft/fft_twiddle_rom.sv: 1024-point twiddle table (indices 0..511), cosine and sine as signed 16-bit.

cos[k] = round(32767 cos(2 pi k / 1024)), sin[k] = round(32767 sin(2 pi k / 1024)).
Run: python3 -I scripts/gen_fft_twiddle.py   (rewrites the RTL file; the output is deterministic).
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "rtl" / "12-fft" / "fft_twiddle_rom.sv"


def table():
    c = [int(math.floor(32767 * math.cos(2 * math.pi * k / 1024) + 0.5)) for k in range(512)]
    s = [int(math.floor(32767 * math.sin(2 * math.pi * k / 1024) + 0.5)) for k in range(512)]
    return c, s


def lit(v):
    return f"-16'sd{-v}" if v < 0 else f"16'sd{v}"


def main():
    c, s = table()
    lines = ["// GENERATED by scripts/gen_fft_twiddle.py - do not edit.",
             "// 1024-point twiddle table: cos and sin of 2*pi*k/1024 for k = 0..511, Q15 (full scale 32767), signed 16 bit.",
             "module fft_twiddle_rom (",
             "    input  logic [8:0]  k,",
             "    output logic [15:0] cos_q,",
             "    output logic [15:0] sin_q",
             ");",
             "  always_comb begin",
             "    case (k)"]
    for i in range(512):
        lines.append(f"      9'd{i}: begin cos_q = {lit(c[i])}; sin_q = {lit(s[i])}; end")
    lines += ["      default: begin cos_q = 16'sd0; sin_q = 16'sd0; end", "    endcase", "  end", "endmodule", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
