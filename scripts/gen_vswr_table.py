#!/usr/bin/env python3
"""Generate fw/33-framework/vswr_table.h: reflection coefficient amplitude in Q15 against the detector difference (reflected - forward) in steps of 0.25 dB
from -40 dB to 0 dB (161 entries). gamma = 10^(delta_dB / 20)."""
from pathlib import Path
rows = []
for i in range(161):
    d = -40.0 + 0.25 * i
    rows.append(min(32767, round(32768 * 10 ** (d / 20))))
out = ["/* generated by scripts/gen_vswr_table.py: reflection coefficient amplitude, Q15, for (reflected - forward) from -40 dB to 0 dB in 0.25 dB steps */",
       "#ifndef VSWR_TABLE_H", "#define VSWR_TABLE_H", "#define VSWR_TAB_N 161", "static const uint16_t vswr_gamma_q15[VSWR_TAB_N] = {"]
for k in range(0, 161, 10):
    out.append("    " + ", ".join(str(v) for v in rows[k:k + 10]) + ",")
out += ["};", "#endif", ""]
Path(__file__).resolve().parent.parent.joinpath("fw", "33-framework", "vswr_table.h").write_text("\n".join(out))
