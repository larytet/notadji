#!/usr/bin/env python3
"""Generate rtl/31-dft-s-ofdm/dfts_twiddle_rom.sv: cos and sin of 2 pi n / M (Q15, signed 16 bit) for M = 48, 96, 192, 384.

cos[n] = floor(32767 cos(2 pi n / M) + 0.5), likewise sin. Run: python3 -I scripts/gen_dfts_twiddle.py
"""
from pathlib import Path

import math

OUT = Path(__file__).resolve().parent.parent / "rtl" / "31-dft-s-ofdm" / "dfts_twiddle_rom.sv"
MS = [48, 96, 192, 384]


def lit(v):
    return f"-16'sd{-v}" if v < 0 else f"16'sd{v}"


def main():
    lines = ["// GENERATED by scripts/gen_dfts_twiddle.py - do not edit.",
             "// cos and sin of 2*pi*n/M for M = 48, 96, 192, 384 (m_sel 0..3), n = 0..M-1, Q15 (full scale 32767), signed 16 bit.",
             "module dfts_twiddle_rom (",
             "    input  logic [1:0]  m_sel,",
             "    input  logic [8:0]  n,",
             "    output logic [15:0] cos_q,",
             "    output logic [15:0] sin_q",
             ");",
             "  always_comb begin",
             "    cos_q = 16'sd0;",
             "    sin_q = 16'sd0;",
             "    case ({m_sel, n})"]
    for sel, m in enumerate(MS):
        for n in range(m):
            a = 2 * math.pi * n / m
            c = int(math.floor(32767 * math.cos(a) + 0.5))
            s = int(math.floor(32767 * math.sin(a) + 0.5))
            lines.append(f"      {{2'd{sel}, 9'd{n}}}: begin cos_q = {lit(c)}; sin_q = {lit(s)}; end")
    lines += ["      default: ;", "    endcase", "  end", "endmodule", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({sum(MS)} entries)")


if __name__ == "__main__":
    main()
