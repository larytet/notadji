#!/usr/bin/env python3
"""Generate rtl/17-equalizer/recip_rom.sv: T[i] = round(2^23 / (256 + i)), i = 0..255 (module 17 reciprocal table)."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "rtl" / "17-equalizer" / "recip_rom.sv"


def main():
    t = [int((2 ** 23) / (256 + i) + 0.5) for i in range(256)]
    L = ["// GENERATED by scripts/gen_recip_rom.py - do not edit.",
         "// Reciprocal table of module 17: T[i] = round(2^23 / (256 + i)).",
         "module recip_rom (", "    input  logic [7:0]  idx,", "    output logic [15:0] t", ");", "  always_comb begin", "    case (idx)"]
    for i, v in enumerate(t):
        L.append(f"      8'd{i}: t = 16'd{v};")
    L += ["      default: t = 16'd0;", "    endcase", "  end", "endmodule", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
