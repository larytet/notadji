#!/usr/bin/env python3
"""Generate the LDPC code tables used by module 13 (encoder) and later the decoder (module 20).

Writes rtl/13-ldpc-encoder/ldpc_code_rom.sv and tests/13-ldpc-encoder/ldpc_codes.json.
Deterministic (seeded). Run: python3 -I scripts/gen_ldpc_codes.py

Codes (code index = {length bit, rate[1:0]}): length 0 = 648 (Z = 27), 1 = 1944 (Z = 81); rate 0..3 = 1/2, 2/3, 3/4, 5/6.
The code N = 648, rate 5/6 is the real IEEE 802.11n code, extracted from the AFF3CT alist; the other seven are own designs
with the same structure (dual-diagonal parity, information columns of degree 3 or 4, no 4-cycles in the base matrix).
"""
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALIST = ROOT / "tests" / "13-ldpc-encoder" / "data" / "WIFI_540_648.alist"
OUT_SV = ROOT / "rtl" / "13-ldpc-encoder" / "ldpc_code_rom.sv"
OUT_JSON = ROOT / "tests" / "13-ldpc-encoder" / "ldpc_codes.json"
NB = 24
MB = {0: 12, 1: 8, 2: 6, 3: 4}
RATE_NAME = {0: "1/2", 1: "2/3", 2: "3/4", 3: "5/6"}


def read_alist(path):
    t = Path(path).read_text().split("\n")
    n, m = map(int, t[0].split())
    cols = [[int(x) - 1 for x in t[4 + j].split() if int(x) > 0] for j in range(n)]
    return n, m, cols


def base_from_alist(path, z):
    n, m, cols = read_alist(path)
    h = [[0] * n for _ in range(m)]
    for j, rs in enumerate(cols):
        for r in rs:
            h[r][j] = 1
    mb, nb = m // z, n // z
    base = [[None] * nb for _ in range(mb)]
    for i in range(mb):
        for j in range(nb):
            blk = [[h[z * i + r][z * j + c] for c in range(z)] for r in range(z)]
            tot = sum(map(sum, blk))
            if tot == 0:
                continue
            assert tot == z, "block is not a circulant permutation"
            s = blk[0].index(1)
            assert all(blk[r][(r + s) % z] == 1 for r in range(z)), "block is not a cyclic shift"
            base[i][j] = s
    return base


def has_4cycle(base, z):
    mb, nb = len(base), len(base[0])
    for i1 in range(mb):
        for i2 in range(i1 + 1, mb):
            seen = set()
            for j in range(nb):
                a, b = base[i1][j], base[i2][j]
                if a is None or b is None:
                    continue
                d = (a - b) % z
                if d in seen:
                    return True
                seen.add(d)
    return False


def design(mb, z, seed):
    nb = NB
    kb = nb - mb
    rng = random.Random(seed)
    base = [[None] * nb for _ in range(mb)]
    x = rng.randrange(1, z)
    base[0][kb] = x
    base[mb // 2][kb] = 0
    base[mb - 1][kb] = x
    for c in range(1, mb):
        base[c - 1][kb + c] = 0
        base[c][kb + c] = 0
    row_deg = [sum(v is not None for v in r) for r in base]
    for j in range(kb):
        d = min(mb, 4 if j % 2 == 0 else 3)
        for attempt in range(5000):
            order = sorted(range(mb), key=lambda i: (row_deg[i] + (rng.random() * (1 + attempt // 50)), i))
            rows = sorted(order[:d])
            for i in rows:
                base[i][j] = rng.randrange(z)
            if not has_4cycle(base, z):
                break
            for i in rows:
                base[i][j] = None
        else:
            raise RuntimeError(f"no 4-cycle-free column found (mb={mb}, z={z}, col={j})")
        for i in rows:
            row_deg[i] += 1
    return base


def build():
    codes = []
    for length in (0, 1):
        n, z = (648, 27) if length == 0 else (1944, 81)
        for rate in range(4):
            mb = MB[rate]
            code = (length << 2) | rate
            if n == 648 and rate == 3:
                base = base_from_alist(ALIST, z)
                src = "standard"
            else:
                base = design(mb, z, seed=1000 + code)
                src = "own"
            kb = NB - mb
            assert not has_4cycle(base, z), f"code {code} has a 4-cycle"
            codes.append(dict(code=code, N=n, K=kb * z, Z=z, mb=mb, kb=kb, rate=RATE_NAME[rate], x=base[0][kb], source=src, base=base))
    return codes


def write_sv(codes):
    L = ["// GENERATED by scripts/gen_ldpc_codes.py - do not edit.",
         "// Base matrices of the eight LDPC codes (design/13-ldpc-encoder.md). code = {length, rate[1:0]}.",
         "module ldpc_code_rom (",
         "    input  logic [2:0] code,",
         "    input  logic [3:0] row,",
         "    input  logic [4:0] col,",
         "    output logic       valid,      // base entry present",
         "    output logic [6:0] shift,",
         "    output logic [6:0] z,",
         "    output logic [3:0] mb,",
         "    output logic [4:0] kb,",
         "    output logic [6:0] xs          // shift x of the first parity column",
         ");",
         "  always_comb begin",
         "    case (code)"]
    for c in codes:
        L.append(f"      3'd{c['code']}: begin z = 7'd{c['Z']}; mb = 4'd{c['mb']}; kb = 5'd{c['kb']}; xs = 7'd{c['x']}; end")
    L += ["      default: begin z = 7'd27; mb = 4'd12; kb = 5'd12; xs = 7'd0; end", "    endcase", "  end", "  always_comb begin",
          "    valid = 1'b0;", "    shift = 7'd0;", "    case ({code, row, col})"]
    for c in codes:
        for i in range(c["mb"]):
            for j in range(c["kb"]):
                v = c["base"][i][j]
                if v is not None:
                    L.append(f"      {{3'd{c['code']}, 4'd{i}, 5'd{j}}}: begin valid = 1'b1; shift = 7'd{v}; end")
    L += ["      default: ;", "    endcase", "  end", "endmodule", ""]
    OUT_SV.write_text("\n".join(L))


def main():
    codes = build()
    write_sv(codes)
    OUT_JSON.write_text(json.dumps(codes, indent=1))
    for c in codes:
        ents = sum(v is not None for r in c["base"] for v in r[:c["kb"]])
        print(f"code {c['code']}: N={c['N']} K={c['K']} rate {c['rate']} Z={c['Z']} mb={c['mb']} source={c['source']} info entries={ents}")
    print(f"wrote {OUT_SV} and {OUT_JSON}")


if __name__ == "__main__":
    main()
